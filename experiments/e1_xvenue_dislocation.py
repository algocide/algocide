#!/usr/bin/env python3
"""E1: H1 cross-venue dislocation, H2 funding differential, H3 weekend drift — xyz:GOLD / xyz:CL vs Binance/OKX.
Pre-registered in docs/hypotheses_and_preregistration.md. Outputs results/e1/*.json, *.csv, *.md, *.png
"""
import os, sys, json, itertools
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "src"))
from hlr.costs import FEE_REGIMES
from hlr.stats import hac_regression, circular_block_bootstrap_ci, describe_pnl, deflated_sharpe, sharpe

OUT = os.path.join(ROOT, "results", "e1"); os.makedirs(OUT, exist_ok=True)
DEV_END = pd.Timestamp("2026-07-01", tz="UTC")
IMPACT_BPS = 0.5
ASSETS = {"gold": {"hl": "xyz:GOLD", "cex_fee_bps": 5.0, "bn_interval_h": 8, "ok_interval_h": 8},
          "wti": {"hl": "xyz:CL", "cex_fee_bps": 5.0, "bn_interval_h": 4, "ok_interval_h": 8}}
# Binance XAUUSDT funding interval = 8h since 2026-01-30 (Binance announcement via search); CLUSDT launched with 4h
# settlement (news via search) -- not re-verified for 2026; OKX default 8h. CEX taker 5 bps = Binance VIP0 USDT-M
# (unverified here). All flagged in docs.


def load(asset):
    df = pd.read_parquet(os.path.join(ROOT, "data", "derived", "perp_basis_5m.parquet"))
    df = df[df["asset"] == asset]
    live = df[df["venue"].isin(["hyperliquid", "binance", "okx"])]
    cols = {}
    for v, tag in [("hyperliquid", "hl"), ("binance", "bn"), ("okx", "ok")]:
        x = live[live["venue"] == v].set_index("ts")
        x = x[~x.index.duplicated()]
        for c, name in [("bid", "bid"), ("ask", "ask"), ("mark_price", "mark"), ("funding_rate", "fund"),
                        ("open_interest", "oi"), ("quote_volume_24h", "qvol")]:
            cols[f"{tag}_{name}"] = x[c]
    w = pd.DataFrame(cols).sort_index()
    for tag in ["hl", "bn", "ok"]:
        bad = (w[f"{tag}_bid"] <= 0) | (w[f"{tag}_ask"] <= 0) | (w[f"{tag}_bid"] > w[f"{tag}_ask"])
        w.loc[bad, [f"{tag}_bid", f"{tag}_ask"]] = np.nan
        w[f"{tag}_mid"] = (w[f"{tag}_bid"] + w[f"{tag}_ask"]) / 2
    # sanity: drop rows where HL deviates >3% from OKX (data errors)
    dev = (w["hl_mid"] / w["ok_mid"] - 1).abs()
    w = w[~(dev > 0.03)]
    w = w[w["hl_mid"].notna()]
    cme = df[df["venue"] == "cme_yahoo"].set_index("ts")[["last_price", "data_age_sec"]].sort_index()
    cme = cme[~cme.index.duplicated()]
    return w, cme


def fwd_ok(ts: pd.DatetimeIndex, h: int, lo=4.0, hi=7.0):
    gap = pd.Series(ts).diff().shift(-1).dt.total_seconds().values / 60.0
    v = ((gap >= lo) & (gap <= hi)).astype(float)
    r = pd.Series(v).rolling(h).min().shift(-(h - 1)).values
    return np.nan_to_num(r, nan=0.0) > 0.5


def simulate(w, s, theta, H, delay=1):
    ts = w.index; n = len(w)
    hl_bid = w["hl_bid"].values; hl_ask = w["hl_ask"].values; sv = s.values
    gap_next = pd.Series(ts).diff().shift(-1).dt.total_seconds().values / 60.0
    trades = []; i = 0
    while i < n - 2:
        si = sv[i]
        if np.isnan(si) or abs(si) < theta:
            i += 1; continue
        side = 1 if si <= -theta else -1
        e = i + delay
        if e >= n or (delay == 1 and not (4 <= gap_next[i] <= 7)):
            i += 1; continue
        entry_px = hl_ask[e] if side == 1 else hl_bid[e]
        if np.isnan(entry_px):
            i += 1; continue
        t_entry = ts[e]; j = e + 1; exit_idx = None
        while j < n:
            sj = sv[j]
            cond = (not np.isnan(sj)) and ((abs(sj) <= theta / 2) or (np.sign(sj) == side))
            timeout = (ts[j] - t_entry) >= pd.Timedelta(minutes=5 * H)
            if cond or timeout:
                x = j + delay
                if x >= n:
                    break
                exit_idx = x; break
            j += 1
        if exit_idx is None:
            break
        exit_px = hl_bid[exit_idx] if side == 1 else hl_ask[exit_idx]
        if np.isnan(exit_px):
            i = exit_idx + 1; continue
        gross = side * 1e4 * np.log(exit_px / entry_px)
        trades.append(dict(t_signal=ts[i], t_entry=t_entry, t_exit=ts[exit_idx], side=side, s_entry=float(si),
                           gross_bps=float(gross), hold_min=(ts[exit_idx] - t_entry).total_seconds() / 60.0,
                           exec_gap_min=float((ts[exit_idx] - ts[j]).total_seconds() / 60.0)))
        i = exit_idx + 1
    return pd.DataFrame(trades)


def stats_block(net, per_day_n=None):
    d = describe_pnl(net)
    if d["n"] >= 5:
        _, lo, hi = circular_block_bootstrap_ci(net, block=5, n_boot=2000)
        d["ci95_lo"], d["ci95_hi"] = lo, hi
    return d


def main():
    report = {}; md = ["# E1 results — cross-venue dislocation (H1), funding differential (H2), weekend drift (H3)\n"]
    md.append("Generated by experiments/e1_xvenue_dislocation.py. Data: data/derived/perp_basis_5m.parquet (see provenance.json).\n")
    grid_rows = []
    for asset, cfg in ASSETS.items():
        w, cme = load(asset)
        rep = {"n_snapshots": int(len(w)), "ts_min": str(w.index.min()), "ts_max": str(w.index.max())}
        md.append(f"\n## {asset} ({cfg['hl']}) — {len(w)} snapshots {w.index.min():%Y-%m-%d} → {w.index.max():%Y-%m-%d}\n")
        # spreads / liquidity
        hs = 1e4 * (w["hl_ask"] - w["hl_bid"]) / w["hl_mid"]
        rep["hl_spread_bps_q50"] = float(hs.median()); rep["hl_spread_bps_q90"] = float(hs.quantile(.9))
        rep["hl_qvol24h_median_usd"] = float(w["hl_qvol"].median()); rep["hl_oi_median"] = float(w["hl_oi"].median())
        md.append(f"HL quoted spread median {hs.median():.2f} bps (q90 {hs.quantile(.9):.2f}); 24h quote volume median ${w['hl_qvol'].median():,.0f}; OI median {w['hl_oi'].median():,.0f} units.\n")
        refs = {"bn": w["bn_mid"], "ok": w["ok_mid"], "avg": (w["bn_mid"] + w["ok_mid"]) / 2}
        rep["refs"] = {}
        for rname, ref in refs.items():
            s = 1e4 * (np.log(w["hl_mid"]) - np.log(ref))
            r = {"n": int(s.notna().sum()), "mean_bps": float(s.mean()), "sd_bps": float(s.std()),
                 "q01": float(s.quantile(.01)), "q99": float(s.quantile(.99)), "abs_gt3_share": float((s.abs() > 3).mean())}
            # AR(1) on consecutive valid steps
            ok1 = fwd_ok(w.index, 1)
            s0 = s.values[:-1][ok1[:-1]]; s1 = s.values[1:][ok1[:-1]]
            m = ~(np.isnan(s0) | np.isnan(s1))
            rho = float(np.corrcoef(s0[m], s1[m])[0, 1]) if m.sum() > 10 else np.nan
            r["ar1_5min"] = rho; r["half_life_min"] = float(-5 * np.log(2) / np.log(rho)) if 0 < rho < 1 else np.nan
            # predictive regressions
            r["regressions"] = {}
            for h in [1, 2, 3, 6, 12]:
                okh = fwd_ok(w.index, h)
                y_hl = 1e4 * (np.log(w["hl_mid"].shift(-h)) - np.log(w["hl_mid"]))
                y_ref = 1e4 * (np.log(ref.shift(-h)) - np.log(ref))
                mask = okh & s.notna().values & y_hl.notna().values & y_ref.notna().values
                if mask.sum() > 50:
                    r["regressions"][h] = {"hl": hac_regression(y_hl.values[mask], s.values[mask], h),
                                           "ref": hac_regression(y_ref.values[mask], s.values[mask], h)}
            # decile table (h=1 and h=6)
            dec = {}
            for h in [1, 6]:
                okh = fwd_ok(w.index, h)
                y_hl = 1e4 * (np.log(w["hl_mid"].shift(-h)) - np.log(w["hl_mid"]))
                y_ref = 1e4 * (np.log(ref.shift(-h)) - np.log(ref))
                mask = okh & s.notna().values & y_hl.notna().values
                dfq = pd.DataFrame({"s": s[mask], "y_hl": y_hl[mask], "y_ref": y_ref[mask]})
                dfq["dec"] = pd.qcut(dfq["s"], 10, labels=False, duplicates="drop")
                g = dfq.groupby("dec").agg(s_mean=("s", "mean"), y_hl=("y_hl", "mean"), y_ref=("y_ref", "mean"), n=("s", "size"))
                dec[h] = g.round(3).to_dict(orient="index")
            r["deciles"] = dec
            rep["refs"][rname] = r
            md.append(f"\n### Reference {rname}: spread s = HL − ref\n")
            md.append(f"mean {r['mean_bps']:.2f} bps, sd {r['sd_bps']:.2f}, 1%/99% = {r['q01']:.2f}/{r['q99']:.2f}, |s|>3bps share {100*r['abs_gt3_share']:.1f}%, AR(1) at 5-min {rho:.3f} (half-life {r['half_life_min']:.1f} min)\n")
            md.append("\n| h (5-min steps) | n | beta HL→(bps/bps) | t(HAC) | beta ref | t(HAC) |\n|---|---|---|---|---|---|")
            for h, rr in r["regressions"].items():
                md.append(f"| {h} | {rr['hl']['n']} | {rr['hl']['beta']:.3f} | {rr['hl']['t_beta_hac']:.2f} | {rr['ref']['beta']:.3f} | {rr['ref']['t_beta_hac']:.2f} |")
            md.append("\nDecile table (h=1 step): mean s, mean forward HL move, mean forward ref move (bps)\n")
            md.append("| decile | s | fwd HL | fwd ref | n |\n|---|---|---|---|---|")
            for k, v in dec[1].items():
                md.append(f"| {k} | {v['s_mean']:.2f} | {v['y_hl']:.3f} | {v['y_ref']:.3f} | {v['n']} |")
        # ---------------- trading grid ----------------
        rep["grid"] = []
        for rname, ref in refs.items():
            s = 1e4 * (np.log(w["hl_mid"]) - np.log(ref))
            for theta, H, delay in itertools.product([1, 2, 3, 5, 8], [6, 12, 36], [1, 0]):
                tr = simulate(w, s, theta, H, delay)
                for fee in ["hip3_standard", "hip3_growth", "zero"]:
                    fee_bps = FEE_REGIMES[fee].taker * 1e4
                    row = {"asset": asset, "ref": rname, "theta": theta, "H": H, "delay": delay, "fee": fee}
                    if len(tr) == 0:
                        row.update({"n_all": 0}); rep["grid"].append(row); grid_rows.append(row); continue
                    net = tr["gross_bps"] - 2 * (fee_bps + IMPACT_BPS)
                    dev = net[tr["t_signal"] < DEV_END]; val = net[tr["t_signal"] >= DEV_END]
                    for tag, x in [("all", net), ("dev", dev), ("val", val)]:
                        d = describe_pnl(x.values)
                        row[f"n_{tag}"] = d["n"]; row[f"mean_{tag}"] = d.get("mean", np.nan); row[f"t_{tag}"] = d.get("t_iid", np.nan)
                        row[f"win_{tag}"] = d.get("win_rate", np.nan); row[f"total_{tag}"] = d.get("total", np.nan)
                        row[f"sr_{tag}"] = d.get("sharpe_per_obs", np.nan); row[f"skew_{tag}"] = d.get("skew", np.nan); row[f"kurt_{tag}"] = d.get("kurt", np.nan)
                    row["gross_mean_all"] = float(tr["gross_bps"].mean()); row["hold_min_mean"] = float(tr["hold_min"].mean())
                    rep["grid"].append(row); grid_rows.append(row)
        g = pd.DataFrame([r for r in rep["grid"] if r.get("n_all", 0) > 0])
        # primary pre-specified variant
        prim = g[(g.ref == "bn") & (g.theta == 3) & (g.H == 12) & (g.delay == 1) & (g.fee == "hip3_standard")]
        md.append("\n### Pre-specified primary variant (ref=Binance, θ=3 bps, H=12 steps, delay=1, standard HIP-3 fees 9 bps taker)\n")
        if len(prim):
            p = prim.iloc[0]
            s = 1e4 * (np.log(w["hl_mid"]) - np.log(w["bn_mid"]))
            tr = simulate(w, s, 3, 12, 1)
            net = (tr["gross_bps"] - 2 * (9.0 + IMPACT_BPS)).values
            bs = stats_block(net)
            rep["primary"] = {"row": p.to_dict(), "bootstrap": bs}
            md.append(f"n={p.n_all} trades (dev {p.n_dev}, val {p.n_val}); gross mean {p.gross_mean_all:.2f} bps; net mean {p.mean_all:.2f} bps [95% block-bootstrap CI {bs.get('ci95_lo', np.nan):.2f}, {bs.get('ci95_hi', np.nan):.2f}]; win rate {100*p.win_all:.0f}%; dev net mean {p.mean_dev:.2f} (t={p.t_dev:.2f}); val net mean {p.mean_val:.2f} (t={p.t_val:.2f}); mean hold {p.hold_min_mean:.0f} min.\n")
            for fee in ["hip3_growth", "zero"]:
                q = g[(g.ref == "bn") & (g.theta == 3) & (g.H == 12) & (g.delay == 1) & (g.fee == fee)].iloc[0]
                md.append(f"Same variant under fee regime {fee}: net mean {q.mean_all:.2f} bps (dev {q.mean_dev:.2f}, val {q.mean_val:.2f}), t_all={q.t_all:.2f}.\n")
        # grid best on development (per fee) with deflated Sharpe
        md.append("\n### Grid search (development period only) and deflated Sharpe\n")
        md.append("| fee | best variant | n dev | net mean dev | t dev | net mean val | t val | n trials | DSR |\n|---|---|---|---|---|---|---|---|---|")
        rep["grid_best"] = {}
        for fee in ["hip3_standard", "hip3_growth", "zero"]:
            gg = g[(g.fee == fee) & (g.n_dev >= 20)].copy()
            if len(gg) == 0:
                md.append(f"| {fee} | (no variant with ≥20 dev trades) | | | | | | | |"); continue
            best = gg.sort_values("sr_dev", ascending=False).iloc[0]
            var_sr = float(gg["sr_dev"].var(ddof=1)) if len(gg) > 1 else 0.0
            ds = deflated_sharpe(best.sr_dev, int(best.n_dev), best.skew_dev, best.kurt_dev, int(len(gg)), var_sr)
            rep["grid_best"][fee] = {"variant": best[["ref", "theta", "H", "delay"]].to_dict(), "n_dev": int(best.n_dev), "mean_dev": float(best.mean_dev),
                                     "t_dev": float(best.t_dev), "mean_val": float(best.mean_val), "t_val": float(best.t_val), "n_val": int(best.n_val),
                                     "n_trials": int(len(gg)), "dsr": ds}
            md.append(f"| {fee} | ref={best.ref}, θ={best.theta}, H={best.H}, delay={best.delay} | {int(best.n_dev)} | {best.mean_dev:.2f} | {best.t_dev:.2f} | {best.mean_val:.2f} | {best.t_val:.2f} | {len(gg)} | {ds['dsr']:.3f} (SR0={ds['sr0']:.3f}) |")
        # ---------------- H2 funding differential ----------------
        md.append("\n### H2 — funding differential (annualised, HL hourly vs CEX per settlement interval)\n")
        f = pd.DataFrame({"hl": w["hl_fund"] * 24 * 365, "bn": w["bn_fund"] / cfg["bn_interval_h"] * 24 * 365, "ok": w["ok_fund"] / cfg["ok_interval_h"] * 24 * 365})
        daily = f.resample("1D").mean().dropna(how="all")
        h2 = {}
        for cex in ["bn", "ok"]:
            d = (daily["hl"] - daily[cex]).dropna()
            ac = float(d.autocorr(1)) if len(d) > 10 else np.nan
            rt_cost = 2 * (9.0 + IMPACT_BPS + 0.12) + 2 * (cfg["cex_fee_bps"] + IMPACT_BPS + 0.02)  # bps, both legs
            res = {"n_days": int(len(d)), "mean_apr": float(d.mean()), "sd_apr": float(d.std()), "daily_autocorr": ac,
                   "share_pos": float((d > 0).mean()), "hl_mean_apr": float(daily["hl"].mean()), f"{cex}_mean_apr": float(daily[cex].mean()),
                   "round_trip_cost_bps_both_legs": rt_cost}
            for hold in [1, 7, 30]:
                # carry earned if the differential is captured for `hold` days at its sample mean of |d|, less costs
                res[f"net_bps_hold{hold}d_mean_absd"] = float(abs(d.mean()) * 1e4 * hold / 365 - rt_cost)
            # realised: sign from trailing 7d mean; held until the sign flips; round trip charged on entry/flip only
            # (first run charged every week -- corrected 2026-09-24, see ledger)
            dd = d.copy(); sig = dd.rolling(7).mean().shift(1)
            wk = []; pos = 0; flips = 0
            for k in range(7, len(dd) - 7, 7):
                sgn = np.sign(sig.iloc[k])
                if sgn == 0 or np.isnan(sgn): continue
                cost = rt_cost if sgn != pos else 0.0; flips += int(cost > 0); pos = sgn
                wk.append(float(sgn * dd.iloc[k:k + 7].mean() * 1e4 * 7 / 365 - cost))
            res["n_flips"] = flips
            res["realised_weekly_net_bps"] = describe_pnl(np.array(wk)) if wk else {"n": 0}
            h2[cex] = res
            md.append(f"- vs {cex}: HL mean {100*res['hl_mean_apr']:.1f}% APR, {cex} mean {100*res[f'{cex}_mean_apr']:.1f}% APR, differential mean {100*res['mean_apr']:.1f}% (sd {100*res['sd_apr']:.1f}%), daily autocorr {ac:.2f}, share positive {100*res['share_pos']:.0f}%; round-trip cost both legs {rt_cost:.1f} bps; realised weekly sign-following net mean {res['realised_weekly_net_bps'].get('mean', np.nan):.1f} bps/week over {res['realised_weekly_net_bps'].get('n',0)} weeks (t={res['realised_weekly_net_bps'].get('t_iid', np.nan):.2f}).")
        rep["h2"] = h2
        # ---------------- H3 weekend drift ----------------
        md.append("\n### H3 — weekend (CME closed Fri 21:00 → Sun 22:00 UTC) drift vs reopen move\n")
        ev = []
        fridays = pd.date_range(w.index.min().normalize(), w.index.max().normalize(), freq="W-FRI", tz="UTC")
        for fr in fridays:
            t_close = fr + pd.Timedelta(hours=21); t_open = fr + pd.Timedelta(days=2, hours=22); t_after = t_open + pd.Timedelta(hours=2)
            def px_at(series, t, before=True, tol=60):
                x = series.dropna()
                if before:
                    x = x[(x.index <= t) & (x.index >= t - pd.Timedelta(minutes=tol))]
                    return x.iloc[-1] if len(x) else np.nan
                x = x[(x.index >= t) & (x.index <= t + pd.Timedelta(minutes=tol))]
                return x.iloc[0] if len(x) else np.nan
            row = {"friday": str(fr.date())}
            for tag in ["hl", "bn", "ok"]:
                p0 = px_at(w[f"{tag}_mid"], t_close); p1 = px_at(w[f"{tag}_mid"], t_open); p2 = px_at(w[f"{tag}_mid"], t_after, before=False)
                row[f"{tag}_weekend_bps"] = 1e4 * np.log(p1 / p0) if p0 and p1 else np.nan
                row[f"{tag}_reopen2h_bps"] = 1e4 * np.log(p2 / p1) if p1 and p2 else np.nan
            c0 = px_at(cme["last_price"], t_close, tol=120); c1 = px_at(cme["last_price"], t_after, before=False, tol=180)
            row["cme_gap_bps"] = 1e4 * np.log(c1 / c0) if c0 and c1 else np.nan
            ev.append(row)
        ev = pd.DataFrame(ev)
        ev.to_csv(os.path.join(OUT, f"h3_weekends_{asset}.csv"), index=False)
        h3 = {"n_events": int(ev["hl_weekend_bps"].notna().sum())}
        for tag in ["hl", "bn"]:
            m = ev[[f"{tag}_weekend_bps", f"{tag}_reopen2h_bps"]].dropna()
            if len(m) >= 5:
                from scipy import stats as sps
                r_, p_ = sps.pearsonr(m.iloc[:, 0], m.iloc[:, 1])
                h3[tag] = {"n": int(len(m)), "corr_weekend_vs_reopen": float(r_), "p": float(p_), "sign_agree": float((np.sign(m.iloc[:, 0]) == np.sign(m.iloc[:, 1])).mean()),
                           "mean_abs_weekend_bps": float(m.iloc[:, 0].abs().mean()), "mean_abs_reopen_bps": float(m.iloc[:, 1].abs().mean())}
        m = ev[["hl_weekend_bps", "cme_gap_bps"]].dropna()
        if len(m) >= 5:
            from scipy import stats as sps
            r_, p_ = sps.pearsonr(m.iloc[:, 0], m.iloc[:, 1])
            h3["hl_weekend_vs_cme_gap"] = {"n": int(len(m)), "corr": float(r_), "p": float(p_)}
        rep["h3"] = h3
        md.append(f"Events with HL data: {h3['n_events']}. " + "; ".join(f"{k}: n={v['n']}, corr(weekend, reopen 2h)={v['corr_weekend_vs_reopen']:.2f} (p={v['p']:.2f}), sign agreement {100*v['sign_agree']:.0f}%" for k, v in h3.items() if isinstance(v, dict) and "corr_weekend_vs_reopen" in v) + (f"; HL weekend move vs CME reopen gap corr {h3['hl_weekend_vs_cme_gap']['corr']:.2f} (n={h3['hl_weekend_vs_cme_gap']['n']})" if "hl_weekend_vs_cme_gap" in h3 else "") + "\n")
        # plots
        fig, ax = plt.subplots(2, 1, figsize=(11, 6), sharex=False)
        s = 1e4 * (np.log(w["hl_mid"]) - np.log(w["bn_mid"]))
        ax[0].plot(s.index, s.values, lw=0.4); ax[0].set_title(f"{cfg['hl']} vs Binance mid spread (bps)"); ax[0].axhline(0, c="k", lw=0.5)
        dq = rep["refs"]["bn"]["deciles"][1]
        ax[1].bar([v["s_mean"] for v in dq.values()], [v["y_hl"] for v in dq.values()], width=0.4, label="fwd HL 5-min move")
        ax[1].bar([v["s_mean"] + 0.4 for v in dq.values()], [v["y_ref"] for v in dq.values()], width=0.4, label="fwd Binance 5-min move")
        ax[1].set_xlabel("spread decile mean (bps)"); ax[1].set_ylabel("bps"); ax[1].legend(); ax[1].set_title("Forward moves by spread decile")
        fig.tight_layout(); fig.savefig(os.path.join(OUT, f"e1_{asset}.png"), dpi=110); plt.close(fig)
        report[asset] = rep
    pd.DataFrame(grid_rows).to_csv(os.path.join(OUT, "grid.csv"), index=False)
    json.dump(report, open(os.path.join(OUT, "e1_results.json"), "w"), indent=1, default=str)
    open(os.path.join(OUT, "e1_summary.md"), "w").write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
